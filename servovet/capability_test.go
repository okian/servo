package servovet

import (
	"strings"
	"testing"
)

// A capability-named method with the wrong signature is never called —
// detection is by signature alone — so the analyzer names it on the types a
// constructor in the package returns. A Close or Shutdown alone is not
// flagged here: on a type the analyzer cannot tell is a graph node, that
// would fire on every closable thing; `servo generate` hints about it for
// the nodes it knows are in the graph.
func TestFlagsCapabilityNearMisses(t *testing.T) {
	const src = `package fixture

import "context"

type Pool struct{}

func NewPool() *Pool        { return &Pool{} }
func (*Pool) Close() error { return nil }

type Consumer struct{}

func NewConsumer(p *Pool) *Consumer { return &Consumer{} }
func (*Consumer) Run() error        { return nil }

type Cache struct{}

func NewCache() *Cache                  { return &Cache{} }
func (*Cache) Stop(ctx context.Context) {}

type Server struct{}

func NewServer(c *Consumer, k *Cache) *Server       { return &Server{} }
func (*Server) Shutdown(ctx context.Context) error { return nil }
func (*Server) Init() error                        { return nil }

// Twice returned, once reported.
func NewServerToo() *Server { return &Server{} }

// Not a constructor's result, so not a node: left alone.
type Loose struct{}

func (*Loose) Run() error { return nil }
`
	got := runOn(t, src)
	want := []string{
		"Run has the signature Run() error, not Run(ctx context.Context) error, so servo will never call it — it has the name of servo's Runner capability",
		"Stop has the signature Stop(ctx context.Context), not Stop(ctx context.Context) error",
		"Init has the signature Init() error, not Init(ctx context.Context) error",
	}
	if len(got) != len(want) {
		t.Fatalf("got %d diagnostics, want %d: %v", len(got), len(want), got)
	}
	joined := strings.Join(got, "\n")
	for _, w := range want {
		if !strings.Contains(joined, w) {
			t.Errorf("diagnostics %v do not contain %q", got, w)
		}
	}
}

// The generated App has Health and Ready methods with a contract of their
// own, and New returns it: a generated file is never this check's business.
func TestCapabilityNearMissesSkipGeneratedFiles(t *testing.T) {
	const src = `// Code generated by servo. DO NOT EDIT.

package fixture

import "context"

type App struct{}

type Report struct{}

func New(ctx context.Context) (*App, error)        { return &App{}, nil }
func (*App) Health(ctx context.Context) Report      { return Report{} }
func (*App) Ready(ctx context.Context) Report       { return Report{} }
`
	if got := runOn(t, src); len(got) != 0 {
		t.Fatalf("got %v in a generated file, want nothing", got)
	}
}
