// TestFindSpecReportsTheSpecFilesOwnTypeErrors covers a marker the type
// checker could not resolve. Servo reads markers through the type checker,
// so a mistyped type name or a package the spec forgot to import leaves
// the marker with no information at all — and that used to be reported as
// "servo.Root must be instantiated with explicit type arguments", sending
// the user after a mistake they had not made. Nothing else ever compiles a
// spec file, so the compiler's own "undefined: api.Sever" has to come from
// servo; a gopls rename that cannot see tagged files is how it happens
// every day.
func TestFindSpecReportsTheSpecFilesOwnTypeErrors(t *testing.T) {
	cases := []struct {
		name, marker, want string
	}{
		{"a mistyped type name", "\t\tservo.Root[*api.Sever](),\n", "undefined: api.Sever"},
		{"a package the spec did not import", "\t\tservo.Bind[store.Store, *redis.Client](),\n", "undefined: redis"},
		{"a mistyped marker", "\t\tservo.Rot[*api.Server](),\n", "undefined: servo.Rot"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			dir := writeFixtureModule(t, c.marker)
			_, err := FindSpec(mustLoad(t, Config{Dir: dir}))
			if err == nil || !strings.Contains(err.Error(), "the spec file does not type-check") || !strings.Contains(err.Error(), c.want) {
				t.Fatalf("got %v, want the type checker's %q", err, c.want)
			}
			if strings.Contains(err.Error(), "must be instantiated with explicit type arguments") {
				t.Errorf("got %v, which still guesses at the cause", err)
			}
		})
	}
}

// TestFindSpecsReportsABuildCallItCannotRead covers the one call servo has
// to recognize before it can read anything: a spec whose servo.Build does
// not resolve holds no call at all, and "run `servo init`" is the wrong
// advice for a file that is right there.
func TestFindSpecsReportsABuildCallItCannotRead(t *testing.T) {
	dir := t.TempDir()
	mustWriteFile(t, dir, "go.mod", "module example.com/buidl\n\ngo 1.23\n\nrequire github.com/okian/servo/v3 v3.0.0\n\nreplace github.com/okian/servo/v3 => "+repoRoot(t)+"\n")
	mustWriteFile(t, dir, "cmd/app/main.go", "package main\n\nfunc main() {}\n")
	mustWriteFile(t, dir, "cmd/app/spec.go", "//go:build servoinject\n\npackage main\n\nimport \"github.com/okian/servo/v3/servo\"\n\nfunc wire() { servo.Buidl(servo.Root[*int]()) }\n")
	runGoModTidy(t, dir)

	_, err := FindSpecs(mustLoad(t, Config{Dir: dir}))
	if err == nil || !strings.Contains(err.Error(), "no servo.Build(...) call could be read") || !strings.Contains(err.Error(), "undefined: servo.Buidl") || strings.Contains(err.Error(), "servo init") {
		t.Fatalf("got %v, want the spec file's type error instead of `servo init`", err)
	}
}

// writeBindModule is a module whose spec binds store.Store — Get and Put —
// to implementations that each fall short in one way the compiler names.
func writeBindModule(t *testing.T, binds string) string {
	t.Helper()
	dir := t.TempDir()
	write := func(rel, content string) { mustWriteFile(t, dir, rel, content) }
	write("go.mod", "module example.com/binds\n\ngo 1.23\n\nrequire github.com/okian/servo/v3 v3.0.0\n\nreplace github.com/okian/servo/v3 => "+repoRoot(t)+"\n")
	write("store/store.go", "package store\n\ntype Store interface {\n\tGet(key string) string\n\tPut(key, value string)\n}\n")
	write("cache/cache.go", "package cache\n\ntype Cache struct{}\n\nfunc (c *Cache) Get(key string) string { return \"\" }\n\nfunc New() *Cache { return &Cache{} }\n")
	write("value/value.go", "package value\n\ntype Value struct{}\n\nfunc (v *Value) Get(key string) string { return \"\" }\n\nfunc (v *Value) Put(key, value string) {}\n\nfunc New() Value { return Value{} }\n")
	write("wrong/wrong.go", "package wrong\n\ntype Wrong struct{}\n\nfunc (w *Wrong) Get(key int) string { return \"\" }\n\nfunc (w *Wrong) Put(key, value string) {}\n\nfunc New() *Wrong { return &Wrong{} }\n")
	write("mocks/store.go", "// Code generated by MockGen. DO NOT EDIT.\n\npackage mocks\n\ntype Store struct{}\n\nfunc (m *Store) Get(key string) string { return \"\" }\n\nfunc New() *Store { return &Store{} }\n")
	write("api/api.go", "package api\n\nimport \"example.com/binds/store\"\n\ntype Server struct{ s store.Store }\n\nfunc New(s store.Store) *Server { return &Server{s: s} }\n")
	write("spec/spec.go", `//go:build servoinject

package spec

import (
	"example.com/binds/api"
	"example.com/binds/cache"
	"example.com/binds/mocks"
	"example.com/binds/store"
	"example.com/binds/value"
	"example.com/binds/wrong"
	"github.com/okian/servo/v3/servo"
)

var (
	_ = cache.New
	_ = mocks.New
	_ = value.New
	_ = wrong.New
)

func Wire() {
	servo.Build(
		servo.Root[*api.Server](),
`+binds+`	)
}
`)
	runGoModTidy(t, dir)
	return dir
}

// TestBindToATypeThatDoesNotImplementTheInterface covers a Bind or
// Override whose concrete type cannot stand in for the interface. It used
// to parse, resolve, and end as a compile error inside the generated file,
// reported as a bug in servo. The everyday cause is a mock older than its
// interface — go generate runs servo before mockgen when servo's directive
// comes first — so a type that reads like generated code gets the hint.
func TestBindToATypeThatDoesNotImplementTheInterface(t *testing.T) {
	cases := []struct {
		name, decl string
		want       []string
		mockHint   bool
	}{
		{
			name: "a missing method",
			decl: "\t\tservo.Bind[store.Store, *cache.Cache](),\n",
			want: []string{"servo.Bind[store.Store, *cache.Cache](): *cache.Cache does not implement store.Store (missing method Put)"},
		},
		{
			name: "a pointer receiver on a value type",
			decl: "\t\tservo.Bind[store.Store, value.Value](),\n",
			want: []string{"value.Value does not implement store.Store (method Get has a pointer receiver, so only *value.Value does — bind that instead)"},
		},
		{
			name: "the wrong signature",
			decl: "\t\tservo.Bind[store.Store, *wrong.Wrong](),\n",
			want: []string{"*wrong.Wrong does not implement store.Store (wrong type for method Get: *wrong.Wrong has func(key int) string, store.Store wants func(key string) string)"},
		},
		{
			name:     "a stale mock, through Override",
			decl:     "\t\tservo.Bind[store.Store, *value.Value](),\n\t\tservo.Override[store.Store, *mocks.Store](),\n",
			want:     []string{"servo.Override[store.Store, *mocks.Store](): *mocks.Store does not implement store.Store (missing method Put)"},
			mockHint: true,
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			dir := writeBindModule(t, c.decl)
			_, err := FindSpec(mustLoad(t, Config{Dir: dir}))
			if err == nil {
				t.Fatal("FindSpec accepted the declaration")
			}
			for _, want := range c.want {
				if !strings.Contains(err.Error(), want) {
					t.Errorf("got %v\nwant it to contain %q", err, want)
				}
			}
			if got := strings.Contains(err.Error(), "regenerate it"); got != c.mockHint {
				t.Errorf("mock hint present = %v, want %v:\n%v", got, c.mockHint, err)
			}
			if !strings.Contains(err.Error(), "spec.go:") {
				t.Errorf("got %v, want it positioned at the marker", err)
			}
		})
	}

	// And the shapes that do implement it still parse.
	dir := writeBindModule(t, "\t\tservo.Bind[store.Store, *value.Value](),\n")
	if _, err := FindSpec(mustLoad(t, Config{Dir: dir})); err != nil {
		t.Fatalf("FindSpec on a Bind that implements the interface: %v", err)
	}
}

// writeStubRuntimeModule is a module whose go.mod replaces servo with a
// stand-in runtime declaring only what runtimeSrc declares — an older or a
// newer release than this CLI, as far as the spec file can tell.
func writeStubRuntimeModule(t *testing.T, runtimeSrc, specArgs string) string {
	t.Helper()
	dir := t.TempDir()
	write := func(rel, content string) { mustWriteFile(t, dir, rel, content) }
	write("runtime/go.mod", "module github.com/okian/servo/v3\n\ngo 1.23\n")
	write("runtime/servo/servo.go", "package servo\n\ntype Marker struct{}\n\nfunc Build(...Marker) {}\n\nfunc Root[T any]() Marker { return Marker{} }\n"+runtimeSrc)
	write("app/go.mod", "module example.com/skew\n\ngo 1.23\n\nrequire github.com/okian/servo/v3 v3.0.0\n\nreplace github.com/okian/servo/v3 => ../runtime\n")
	write("app/api/api.go", "package api\n\ntype Server struct{}\n\nfunc New() *Server { return &Server{} }\n")
	write("app/spec/spec.go", "//go:build servoinject\n\npackage spec\n\nimport (\n\t\"example.com/skew/api\"\n\t\"github.com/okian/servo/v3/servo\"\n)\n\nfunc Wire() {\n\tservo.Build(\n\t\tservo.Root[*api.Server](),\n"+specArgs+"\t)\n}\n")
	return dir + "/app"
}

// TestMarkerSkewNamesBothVersions covers a CLI and a runtime that disagree
// about the markers. The spec file is checked against the runtime go.mod
// resolves, while the markers servo reads are the CLI's: an older runtime
// hands it a spec using a marker it does not declare, and a newer one a
// marker the CLI has never heard of — which read `unrecognized servo
// marker "Trace"`, as if the spec were wrong.
func TestMarkerSkewNamesBothVersions(t *testing.T) {
	t.Run("a runtime older than the CLI", func(t *testing.T) {
		dir := writeStubRuntimeModule(t, "", "\t\tservo.Trace[*api.Server](),\n")
		_, err := FindSpec(mustLoad(t, Config{Dir: dir, CLIVersion: "v3.9.0"}))
		for _, want := range []string{"servo.Trace is a marker servo v3.9.0 knows", "does not declare it", "go get github.com/okian/servo/v3@latest", "go tool servo"} {
			if err == nil || !strings.Contains(err.Error(), want) {
				t.Errorf("got %v\nwant it to contain %q", err, want)
			}
		}
	})
	t.Run("a runtime newer than the CLI", func(t *testing.T) {
		dir := writeStubRuntimeModule(t, "\nfunc Decorate[T any]() Marker { return Marker{} }\n", "\t\tservo.Decorate[*api.Server](),\n")
		_, err := FindSpec(mustLoad(t, Config{Dir: dir}))
		for _, want := range []string{"servo.Decorate is a marker " + graph.ServoPackagePath + ", which the module requires, declares and this servo CLI does not know", "go tool servo generate"} {
			if err == nil || !strings.Contains(err.Error(), want) {
				t.Errorf("got %v\nwant it to contain %q", err, want)
			}
		}
	})
	t.Run("both versions known", func(t *testing.T) {
		e := &markerSkewError{pos: token.Position{Filename: "spec.go", Line: 9, Column: 3}, name: "Trace", kind: "marker", cliKnows: true, cli: "v3.9.0", runtime: "v3.3.0"}
		if want := "spec.go:9:3: servo.Trace is a marker servo v3.9.0 knows, but " + graph.ServoPackagePath + " v3.3.0, which the module requires, does not declare it"; !strings.HasPrefix(e.Error(), want) {
			t.Errorf("Error() = %q\nwant prefix %q", e.Error(), want)
		}
	})
}

// TestKnownMarkersAreTheRuntimesMarkers keeps the CLI's marker list and the
// runtime package's marker functions one set, in both directions: a marker
// added to the runtime without teaching the parser would otherwise ship
// as "a marker this servo does not know" from the very release adding it.
func TestKnownMarkersAreTheRuntimesMarkers(t *testing.T) {
	l := mustLoad(t, Config{Dir: writeFixtureModule(t, "")})
	scope := l.ServoPkg.Types.Scope()
	runtime := map[string]bool{"Build": true}
	for _, name := range scope.Names() {
		fn, ok := scope.Lookup(name).(*types.Func)
		if !ok {
			continue
		}
		for _, result := range []string{"Marker", "HTTPOption", "ScopeOption", "TraceOption"} {
			if returnsServoType(fn, result) {
				runtime[name] = true
			}
		}
	}
	for name := range runtime {
		if !knownMarkers[name] {
			t.Errorf("servo.%s is a marker of the runtime that knownMarkers, and the spec parser, do not know", name)
		}
	}
	for name := range knownMarkers {
		if !runtime[name] {
			t.Errorf("knownMarkers lists servo.%s, which the runtime does not declare as a marker", name)
		}
	}
}
